/**
 * このサーバーが載せているツールの識別子（#95 S4b）。
 *
 * **綴りの正本はここ 1 つである。** `@tasuki/room-core` は `ToolId` を不透明な文字列
 * として扱い（設計正本 §5.1）、どのツールが実在するかを知らない。知っているのは
 * 合成ルートであるこのアプリだけなので、リテラルをここへ集める。
 *
 * ## 誰がこの値を決めるのか
 *
 * **接続 URL のクエリ（`?tool=`）が宣言そのものである**（設計正本 D14 の S4b 追記・
 * #95 S5c で経路からクエリへ移った）。`adapters/ws-adapter.ts` の
 * `protocolFromRequestUrl` が読み、poker と timer を振り分ける（`ws.data.protocol`）。
 * したがって timer のハンドラへ届いた接続は定義上 timer の接続であり、各入口は
 * 定数を渡すだけでよい。**wire には `tool` を載せない** ——
 * 載せるとクライアントが入口と矛盾する値を送れるようになり、突き合わせの検査が
 * 新たに要る（poker の入口から `"timer"` を宣言されたら在席が嘘になる）。
 *
 * ハブ（`tool: null`）は選択画面に居る接続で、S5a（#247）から実際に使われている。
 *
 * ## 同じ綴りが wire にも載る
 *
 * 「載せない」のは**接続がどのツールかの宣言**であって、値そのものではない。
 * 在席の欄 `roster.tools`（`packages/room-core/src/wire.ts` の `RosterParticipant`）は
 * この綴りをそのままクライアントへ運ぶ。**したがってここを改名すると wire 互換が壊れる。**
 * 接続 URL のクエリ（`?tool=`）も同じ綴りなので、古いクライアントは繋がらなくなる。
 *
 * **ツール状態の遅延生成もこの値で決まる**（#95 S5b）。`join-room.ts` は
 * `TOOL_TIMER` の接続に対してだけ timer の状態を作る —— ハブの接続が作ってしまうと、
 * 誰も timer を開いていないルームにタイマーが生まれる。
 */

/** timer（モブタイマー）の入口から来た接続。 */
export const TOOL_TIMER = "timer";

/** poker（見積もり）の入口から来た接続。 */
export const TOOL_POKER = "poker";

/** お題ツールの入口から来た接続（#91）。 */
export const TOOL_TOPIC = "topic";
