/**
 * このサーバーが載せているツールの識別子（#95 S4b）。
 *
 * **綴りの正本はここ 1 つである。** `@tasuki/room-core` は `ToolId` を不透明な文字列
 * として扱い（設計正本 §5.1）、どのツールが実在するかを知らない。知っているのは
 * 合成ルートであるこのアプリだけなので、リテラルをここへ集める。
 *
 * ## 誰がこの値を決めるのか
 *
 * **接続が来た入口が宣言そのものである**（設計正本 D14 の S4b 追記）。
 * `adapters/ws-adapter.ts` は `/poker/ws` に来た接続を poker、それ以外を timer として
 * 扱う（`ws.data.protocol`）。したがって timer のハンドラへ届いた接続は定義上
 * timer の接続であり、各入口は定数を渡すだけでよい。**wire には `tool` を載せない** ——
 * 載せるとクライアントが入口と矛盾する値を送れるようになり、突き合わせの検査が
 * 新たに要る（poker の入口から `"timer"` を宣言されたら在席が嘘になる）。
 *
 * ハブ（`tool: null`）を作る経路は S5a（#247）で現れる。それまで `null` を渡すのは
 * 在席判定のテストだけである。
 *
 * **入口の門（`tool-gate.ts`）の引数と同じ値域である。** 門は「その入口からそのルームへ
 * 入ってよいか」、こちらは「その接続がどのツールに居るか」を指す。**同じ入口の話なので
 * 綴りが食い違ってはならない。**
 */

/** timer（モブタイマー）の入口から来た接続。 */
export const TOOL_TIMER = "timer";

/** poker（見積もり）の入口から来た接続。 */
export const TOOL_POKER = "poker";
