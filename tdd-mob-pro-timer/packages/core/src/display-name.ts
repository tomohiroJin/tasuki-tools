/**
 * 表示名の正規化（信頼境界で一度だけ適用する）。
 *
 * 表示名は「人を見分けるための唯一の手掛かり」なので、**画面で同じに見えるものは
 * 同じ文字列である**という性質が要る。そうでないと、同名判定（`participant-label`）が
 * 発火せず識別子も添えられないまま、見分けの付かない行が並ぶ。
 * 実機検証では次が素通りしていた:
 *
 *   - `"  Bob  "` … HTML は空白を畳むので画面では `Bob`。だが文字列は別物なので
 *     重複と判定されず、識別子も付かない（完全な見分け不能）
 *   - `"Bob\nAdmin"` … 改行も畳まれて `Bob Admin` に見える
 *   - `"   "` … 空欄の行になる
 *   - `"Bob（ID: 0x3P）"` … 識別子の書式そのものを名乗り、実在の参加者になりすませる
 *
 * `participant.rename` / `participant.addProxy` は比較時に `trim()` していたが、
 * `room.join` / `room.create` は保存時に何もしていなかった。入口ごとに扱いが違うと
 * 必ずどこかが抜けるので、**境界のスキーマで正規化して以後は正規形しか流れない**ようにする。
 */

/**
 * 識別子つきの呼び名（`participant-label.ts` が生成する `（ID: xxxx）`）の書式。
 *
 * 利用者がこの書式を名乗れると、「名前が衝突したときの最後の拠り所」である識別子を
 * 偽造できてしまう。実機では実在の参加者と**完全に同一のラベル**（退出ボタン・確認
 * ダイアログ・通知のすべて）を作れた。生成物と利用者入力が同じ文字列に同居する以上、
 * 入力側からこの書式を取り除くのが確実である。
 *
 * 全角/半角の括弧とコロン、`ID` の大小・前後の空白を許容して広めに剥がす。
 */
const LABEL_MARKER = /[（(]\s*ID\s*[:：][^）)]*[）)]/gi;

/**
 * 制御文字（C0/C1）。画面や読み上げを壊すため落とす。
 *
 * タブ・改行・復帰は**除かない**。これらは「空白として畳む」対象であり、
 * 先に消すと `"Bob\nAdmin"` が `"BobAdmin"` になって語が繋がってしまう。
 */
// eslint-disable-next-line no-control-regex
const CONTROL_CHARS = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f-\u009f]/g;

/**
 * 表示名を正規形へ直す。
 *
 * 1. 識別子ラベルの書式を落とす（なりすまし防止）
 * 2. 制御文字を落とす（タブ・改行は次段で空白に畳むので残す）
 * 3. 連続する空白（改行・タブ・全角空白を含む）を1つの半角空白に畳む
 * 4. 前後の空白を落とす
 *
 * 結果が空文字になることがある（`"   "` など）。**空の可否は呼び出し側で判定する**
 * （境界スキーマは正規化後に最小長を課して弾く）。
 */
export function normalizeDisplayName(raw: string): string {
  return raw
    .replace(LABEL_MARKER, "")
    .replace(CONTROL_CHARS, "")
    .replace(/\s+/g, " ")
    .trim();
}
